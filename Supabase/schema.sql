create or replace function public.create_school(
  p_admin_key text,
  p_name text,
  p_password text,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  created_school record;
  table_name text := public.site_schools_table(p_site);
begin
  if not public.admin_password_matches(p_admin_key, p_site) then
    raise exception 'Incorrect admin password' using errcode = '28000';
  end if;

  if nullif(trim(p_name), '') is null or nullif(p_password, '') is null then
    raise exception 'School name and password are required' using errcode = '22023';
  end if;

  execute format(
    'insert into public.%I (school, password, progress, comments)
     values (trim($1), $2, public.default_progress_steps(), ''[]''::jsonb)
     returning *',
    table_name
  )
  into created_school
  using p_name, p_password;

  return jsonb_build_object(
    'school', created_school.school,
    'progress', created_school.progress,
    'comments', created_school.comments
  );
exception
  when unique_violation then
    raise exception 'School already exists' using errcode = '23505';
end;
$$;

