create or replace function public.add_comment(
  p_school_name text,
  p_school_key text,
  p_text text,
  p_admin_key text default null,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  school_row record;
  current_comments jsonb;
  new_comment jsonb;
  new_index integer;
  sender text;
  table_name text := public.site_schools_table(p_site);
begin
  if nullif(trim(p_text), '') is null then
    raise exception 'Comment text is required' using errcode = '22023';
  end if;

  if p_admin_key is not null and not public.admin_password_matches(p_admin_key, p_site) then
    raise exception 'Incorrect admin key' using errcode = '28000';
  end if;

  execute format(
    'select *
     from public.%I sp
     where lower(sp.school) = lower(trim($1))
       and sp.password = $2
     for update',
    table_name
  )
  into school_row
  using p_school_name, p_school_key;

  if school_row is null then
    raise exception 'School not found or incorrect password' using errcode = '28000';
  end if;

  current_comments := coalesce(school_row.comments, '[]'::jsonb);
  new_index := jsonb_array_length(current_comments);
  sender := case when p_admin_key is null then 'school' else 'leonardo' end;
  new_comment := jsonb_build_object('index', new_index, 'sender', sender, 'text', p_text, 'viewed', false);

  execute format(
    'update public.%I
     set comments = $1 || jsonb_build_array($2)
     where id = $3',
    table_name
  )
  using current_comments, new_comment, school_row.id;

  return jsonb_build_object('success', true, 'comment', new_comment);
end;
$$;

create or replace function public.delete_comment(
  p_school_name text,
  p_school_key text,
  p_comment_index integer,
  p_admin_key text,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  school_row record;
  updated_comments jsonb;
  table_name text := public.site_schools_table(p_site);
begin
  if not public.admin_password_matches(p_admin_key, p_site) then
    raise exception 'Incorrect admin key' using errcode = '28000';
  end if;

  execute format(
    'select *
     from public.%I sp
     where lower(sp.school) = lower(trim($1))
       and sp.password = $2
     for update',
    table_name
  )
  into school_row
  using p_school_name, p_school_key;

  if school_row is null then
    raise exception 'School not found or incorrect password' using errcode = '28000';
  end if;

  if p_comment_index < 0 or p_comment_index >= jsonb_array_length(school_row.comments) then
    raise exception 'Invalid comment index' using errcode = '22023';
  end if;

  select coalesce(
    jsonb_agg((comment - 'index') || jsonb_build_object('index', new_index) order by new_index),
    '[]'::jsonb
  )
  into updated_comments
  from (
    select
      comment,
      row_number() over (order by ordinality) - 1 as new_index
    from jsonb_array_elements(school_row.comments) with ordinality as items(comment, ordinality)
    where (comment->>'index')::integer <> p_comment_index
  ) reindexed;

  execute format(
    'update public.%I
     set comments = $1
     where id = $2',
    table_name
  )
  using updated_comments, school_row.id;

  return jsonb_build_object('success', true, 'comments', updated_comments);
end;
$$;

create or replace function public.mark_comment_viewed(
  p_school_name text,
  p_school_key text,
  p_msg_index integer,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  school_row record;
  updated_comments jsonb;
  viewed_comment jsonb;
  table_name text := public.site_schools_table(p_site);
begin
  execute format(
    'select *
     from public.%I sp
     where lower(sp.school) = lower(trim($1))
       and sp.password = $2
     for update',
    table_name
  )
  into school_row
  using p_school_name, p_school_key;

  if school_row is null then
    raise exception 'School not found or incorrect password' using errcode = '28000';
  end if;

  if p_msg_index < 0 or p_msg_index >= jsonb_array_length(school_row.comments) then
    raise exception 'Invalid message index' using errcode = '22023';
  end if;

  select jsonb_agg(
    case
      when (comment->>'index')::integer = p_msg_index then jsonb_set(comment, '{viewed}', 'true'::jsonb)
      else comment
    end
    order by ordinality
  )
  into updated_comments
  from jsonb_array_elements(school_row.comments) with ordinality as items(comment, ordinality);

  select comment
  into viewed_comment
  from jsonb_array_elements(updated_comments) comment
  where (comment->>'index')::integer = p_msg_index
  limit 1;

  execute format(
    'update public.%I
     set comments = $1
     where id = $2',
    table_name
  )
  using updated_comments, school_row.id;

  return jsonb_build_object('success', true, 'comment', viewed_comment);
end;
$$;

create or replace function public.get_unviewed_comments(
  p_admin_key text,
  p_sent_by text default null,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  result jsonb;
  table_name text := public.site_schools_table(p_site);
begin
  if not public.admin_password_matches(p_admin_key, p_site) then
    raise exception 'Incorrect admin key' using errcode = '28000';
  end if;

  execute format(
    'select coalesce(jsonb_object_agg(school, unviewed_count), ''{}''::jsonb)
     from (
       select sp.school, count(*)::integer as unviewed_count
       from public.%I sp
       cross join lateral jsonb_array_elements(sp.comments) comment
       where sp.school <> ''Admin''
         and (comment->>''viewed'')::boolean = false
         and (
           $1 is null
           or $1 not in (''leonardo'', ''school'')
           or comment->>''sender'' = $1
         )
       group by sp.school
     ) counts',
    table_name
  )
  into result
  using p_sent_by;

  return result;
end;
$$;

