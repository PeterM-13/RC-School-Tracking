create or replace function public.delete_school(
  p_admin_key text,
  p_name text,
  p_password text,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_school text;
  table_name text := public.site_schools_table(p_site);
begin
  if not public.admin_password_matches(p_admin_key, p_site) then
    raise exception 'Incorrect admin password' using errcode = '28000';
  end if;

  execute format(
    'delete from public.%I sp
     where lower(sp.school) = lower(trim($1))
       and sp.password = $2
       and sp.school <> ''Admin''
     returning sp.school',
    table_name
  )
  into deleted_school
  using p_name, p_password;

  if deleted_school is null then
    raise exception 'School not found or incorrect password' using errcode = '02000';
  end if;

  return jsonb_build_object(
    'success', true,
    'message', format('School "%s" deleted successfully', deleted_school)
  );
end;
$$;

