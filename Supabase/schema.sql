create table if not exists public.school_progress (
  id bigint generated by default as identity primary key,
  school text not null,
  password text not null,
  progress jsonb not null default '[]'::jsonb,
  comments jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_progress_school_unique unique (school),
  constraint school_progress_array check (jsonb_typeof(progress) = 'array'),
  constraint school_progress_comments_array check (jsonb_typeof(comments) = 'array')
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_school_progress_updated_at on public.school_progress;
create trigger set_school_progress_updated_at
before update on public.school_progress
for each row
execute function public.set_updated_at();

alter table public.school_progress enable row level security;

drop policy if exists "No direct anon reads" on public.school_progress;
drop policy if exists "No direct anon writes" on public.school_progress;

