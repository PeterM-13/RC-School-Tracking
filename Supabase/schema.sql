create or replace function public.apply_progress_template(p_template jsonb, p_progress jsonb)
returns jsonb
language sql
stable
as $$
  with template as (
    select item, ordinality
    from jsonb_array_elements(p_template) with ordinality as t(item, ordinality)
  ),
  source as (
    select item
    from jsonb_array_elements(p_progress) as s(item)
  )
  select jsonb_agg(
    template.item || jsonb_build_object(
      'checked',
      coalesce((
        select (source.item->>'checked')::boolean
        from source
        where (source.item->>'index')::integer = (template.item->>'index')::integer
        limit 1
      ), false)
    )
    order by template.ordinality
  )
  from template;
$$;

