create or replace function public.reset_all_progress(
  p_admin_key text,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  table_name text := public.site_schools_table(p_site);
begin
  if not public.admin_password_matches(p_admin_key, p_site) then
    raise exception 'Incorrect admin password' using errcode = '28000';
  end if;

  execute format(
    'update public.%I
     set progress = (
       select jsonb_agg(jsonb_set(item, ''{checked}'', ''false''::jsonb) order by ordinality)
       from jsonb_array_elements(progress) with ordinality as steps(item, ordinality)
     )
     where school <> ''Admin''',
    table_name
  );

  return jsonb_build_object('success', true, 'message', 'All school progress has been reset');
end;
$$;

