create or replace function public.site_schools_table(p_site text default 'Luton')
returns text
language sql
stable
as $$
  select case coalesce(nullif(trim(p_site), ''), 'Luton')
    when 'Luton' then 'Luton_schools'
    when 'Edinburgh' then 'Edinburgh_schools'
    when 'Basildon' then 'Basildon_schools'
    else 'Luton_schools'
  end;
$$;

create or replace function public.school_password_matches(
  p_school text,
  p_password text,
  p_site text default 'Luton'
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  matched boolean;
  table_name text := public.site_schools_table(p_site);
begin
  execute format(
    'select exists (
      select 1
      from public.%I sp
      where lower(sp.school) = lower(trim($1))
        and sp.password = $2
    )',
    table_name
  )
  into matched
  using p_school, p_password;

  return matched;
end;
$$;

