$$;

create or replace function public.get_school_progress(p_name text, p_password text)
returns jsonb
language sql
security definer
set search_path = public
as $$
  select coalesce(
    (
      select jsonb_build_object(
        'school',
        sp.school,
        'progress',
        public.apply_progress_template(
          (select admin.progress from public.school_progress admin where admin.school = 'Admin' limit 1),
          sp.progress
        )
      )
      from public.school_progress sp
      where lower(sp.school) = lower(trim(p_name))
        and sp.password = p_password
      limit 1
    ),
    jsonb_build_object('error', 'School not found or incorrect password')
  );
$$;

create or replace function public.list_school_progress(
  p_name text default null,
  p_password text default null,
  p_admin_key text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not (
    public.admin_password_matches(coalesce(p_admin_key, ''))
    or public.school_password_matches(coalesce(p_name, ''), coalesce(p_password, ''))
  ) then
    raise exception 'Not authorised' using errcode = '28000';
  end if;

  return coalesce(
    (
      select jsonb_agg(
        jsonb_build_object(
          'school',
          sp.school,
          'progress',
          public.apply_progress_template(
            (select admin.progress from public.school_progress admin where admin.school = 'Admin' limit 1),
            sp.progress
          )
        )
        order by sp.school
      )
      from public.school_progress sp
    ),
    '[]'::jsonb
  );
end;
$$;

create or replace function public.create_school(p_admin_key text, p_name text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  created_school public.school_progress;
begin
  if not public.admin_password_matches(p_admin_key) then
    raise exception 'Incorrect admin password' using errcode = '28000';
  end if;

  if nullif(trim(p_name), '') is null or nullif(p_password, '') is null then
    raise exception 'School name and password are required' using errcode = '22023';
  end if;

  insert into public.school_progress (school, password, progress, comments)
  values (trim(p_name), p_password, public.default_progress_steps(), '[]'::jsonb)
  returning * into created_school;

  return jsonb_build_object(
    'school', created_school.school,
    'progress', created_school.progress,
    'comments', created_school.comments
  );
exception
  when unique_violation then
    raise exception 'School already exists' using errcode = '23505';
end;
$$;

create or replace function public.delete_school(p_admin_key text, p_name text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_school text;
begin
  if not public.admin_password_matches(p_admin_key) then
    raise exception 'Incorrect admin password' using errcode = '28000';
  end if;

  delete from public.school_progress sp
  where lower(sp.school) = lower(trim(p_name))
    and sp.password = p_password
    and sp.school <> 'Admin'
  returning sp.school into deleted_school;

  if deleted_school is null then
    raise exception 'School not found or incorrect password' using errcode = '02000';
  end if;

  return jsonb_build_object(
    'success', true,
    'message', format('School "%s" deleted successfully', deleted_school)
  );
end;
$$;

create or replace function public.update_school_progress(p_name text, p_password text, p_progress jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_school public.school_progress;
begin
  update public.school_progress sp
  set progress = p_progress
  where lower(sp.school) = lower(trim(p_name))
    and sp.password = p_password
  returning * into updated_school;

  if updated_school.id is null then
    raise exception 'School not found or incorrect password' using errcode = '28000';
  end if;

  return jsonb_build_object('school', updated_school.school, 'progress', updated_school.progress);
end;
$$;

create or replace function public.reset_all_progress(p_admin_key text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.admin_password_matches(p_admin_key) then
    raise exception 'Incorrect admin password' using errcode = '28000';
  end if;

  update public.school_progress
  set progress = (
    select jsonb_agg(jsonb_set(item, '{checked}', 'false'::jsonb) order by ordinality)
    from jsonb_array_elements(progress) with ordinality as steps(item, ordinality)
  )
  where school <> 'Admin';
  return jsonb_build_object('success', true, 'message', 'All school progress has been reset');
end;
$$;

