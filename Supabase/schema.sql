    'select coalesce(
      (
        select jsonb_build_object(''comments'', sp.comments)
        from public.%I sp
        where lower(sp.school) = lower(trim($1))
          and sp.password = $2
        limit 1
      ),
      jsonb_build_object(''error'', ''School not found or incorrect password'')
