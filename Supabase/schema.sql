create or replace function public.get_school_progress(
  p_name text,
  p_password text,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  result jsonb;
  table_name text := public.site_schools_table(p_site);
begin
  execute format(
    'select coalesce(
      (
        select jsonb_build_object(
          ''school'',
          sp.school,
          ''progress'',
          public.apply_progress_template(
            (select admin.progress from public.%1$I admin where admin.school = ''Admin'' limit 1),
            sp.progress
          )
        )
        from public.%1$I sp
        where lower(sp.school) = lower(trim($1))
          and sp.password = $2
        limit 1
      ),
      jsonb_build_object(''error'', ''School not found or incorrect password'')
    )',
    table_name
  )
  into result
  using p_name, p_password;

  return result;
end;
$$;

create or replace function public.list_school_progress(
  p_name text default null,
  p_password text default null,
  p_admin_key text default null,
  p_site text default 'Luton'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  result jsonb;
  table_name text := public.site_schools_table(p_site);
begin
  if not (
    public.admin_password_matches(coalesce(p_admin_key, ''), p_site)
    or public.school_password_matches(coalesce(p_name, ''), coalesce(p_password, ''), p_site)
  ) then
    raise exception 'Not authorised' using errcode = '28000';
  end if;

  execute format(
    'select coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            ''school'',
            sp.school,
            ''progress'',
            public.apply_progress_template(
              (select admin.progress from public.%1$I admin where admin.school = ''Admin'' limit 1),
              sp.progress
            )
          )
          order by sp.school
        )
        from public.%1$I sp
      ),
      ''[]''::jsonb
    )',
    table_name
  )
  into result;

  return result;
end;
$$;

